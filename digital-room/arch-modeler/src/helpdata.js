/**
 * キーワード検索: スコア上位の項目を返す
 * @param {string} query 検索語（空白区切りで複数可）
 * @param {number} limit 最大件数
 */
export function searchHelp(query, limit = 5) {
  const terms = query.trim().toLowerCase().split(/[\s　]+/).filter(t => t.length > 0);
  if (terms.length === 0) return [];
  const scored = HELP_ENTRIES.map(e => {
    let score = 0;
    for (const t of terms) {
      if (e.keywords.some(k => k.toLowerCase().includes(t))) score += 3;
      if (e.q.toLowerCase().includes(t)) score += 2;
      if (e.a.toLowerCase().includes(t)) score += 1;
    }
    return { e, score };
  }).filter(s => s.score > 0);
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map(s => s.e);
}
